package com.smartticket.rag;

/**
 * 检索路径（阶段2 第6天）。
 *
 * <p>存在的意义是章程约束「记录命中来源」：RAG 给出的建议必须能回答
 * "这条依据是语义匹配到的、还是字面匹配到的"。第7天做双路合并时会再加一个
 * {@code BOTH}，用于标记"两条路都召回了它"。</p>
 */
public enum RetrievalSource {

    /** 向量检索：按语义相似度召回。用户说"登不上"也能召回"验证码异常" */
    VECTOR,

    /** 关键词检索：按字符三元组相似度召回。认字面，不认同义改写 */
    KEYWORD

}
