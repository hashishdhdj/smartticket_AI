package com.smartticket.enums;

/**
 * 统一错误码。
 *
 * <p>编号规则（三段式，2026-09-16 决策）：</p>
 * <ul>
 *   <li>0：成功</li>
 *   <li>1xxxx：业务类错误（业务规则不满足，如工单不存在；细分码在各业务实现时补充）</li>
 *   <li>4xxxx：客户端 / 参数类错误（请求参数、报文格式问题）</li>
 *   <li>5xxxx：系统类错误（未预料的异常，对外只给固定文案）</li>
 * </ul>
 *
 * <p>注意：错误码一经对外使用不要复用或改数值，只能新增。</p>
 */
public enum ErrorCode {

    /** 成功 */
    SUCCESS(0, "成功"),

    /** 业务处理失败（默认业务码，具体业务细分码在对应接口实现时补充） */
    BUSINESS_ERROR(10000, "业务处理失败"),

    /** 工单状态流转不合法（如 已关闭 → 待分配） */
    INVALID_STATUS_TRANSITION(10001, "工单状态流转不合法"),

    /** 未知的工单状态值（库里或请求里的值不在已确认的 6 个状态内） */
    UNKNOWN_STATUS_CODE(10002, "未知的工单状态值"),

    /** 工单不存在（按 id 查不到，或已被逻辑删除） */
    TICKET_NOT_FOUND(10003, "工单不存在"),

    /** 工单编号生成冲突（随机重试多次仍撞唯一键） */
    TICKET_NO_CONFLICT(10004, "工单编号生成冲突，请重试"),

    /** 当前工单状态不允许该操作（非状态流转类的拒绝，如已关闭工单被指派） */
    TICKET_STATUS_NOT_ALLOWED(10005, "当前工单状态不允许此操作"),

    /** AI 能力未启用或未配置（未配密钥 / 总开关关闭 / 模型未装配）。属"设计内降级"，不是故障 */
    AI_NOT_CONFIGURED(10006, "AI 能力未配置，已降级为人工处理"),

    /** AI 调用失败（超时、网络不通、模型返回错误码、鉴权失败等），已降级为人工处理 */
    AI_CALL_FAILED(10007, "AI 服务暂时不可用，已降级为人工处理"),

    /**
     * AI 返回内容无法解析为约定结构（不是合法 JSON、字段缺失或多余、取值越界）。
     *
     * <p>与 10007 分开的原因：调用失败是"模型没答话"，解析失败是"模型答了但不守规矩"。
     * 两者排查方向完全不同，统计降级率时也必须分开看——若解析失败占比高，该改的是 Prompt；
     * 若调用失败占比高，该查的是网络与厂商。</p>
     */
    AI_RESPONSE_UNPARSABLE(10008, "AI 返回内容不符合约定格式，已降级为人工处理"),

    /**
     * 向量库不可用（PostgreSQL / pgvector 连不上、表不存在、写入类型不符等）。
     *
     * <p>与 10007 分开的原因：10007 是"模型没答话"，本码是"存/取向量的库出问题"。
     * 两者都不影响工单主流程，但排查动作完全不同——一个查厂商与网络，
     * 一个查 PostgreSQL 容器与连接配置，混在一起会让"RAG 检索为什么空"变得不可定位。</p>
     */
    VECTOR_STORE_UNAVAILABLE(10009, "向量库不可用，RAG 检索已降级"),

    /**
     * 向量库中的数据与当前配置的嵌入模型不一致（换了模型没重建索引）。
     *
     * <p>与 10009 分开的原因：10009 是"库连不上"，本码是"库连得上、但里面的东西不能用来比对"。
     * 不同嵌入模型产出的向量处在<b>不同的向量空间</b>，拿 A 模型的查询向量去和 B 模型的库中向量
     * 算余弦距离，得到的是没有意义的数字——而且<b>不会报错</b>，只会让检索结果变得不可解释。
     * 处置动作也不同：一个查 PostgreSQL 容器，一个重建索引或改回原模型配置。</p>
     */
    VECTOR_MODEL_MISMATCH(10010, "向量库数据与当前嵌入模型不一致，需重建索引"),

    AI_AUTH_FAILED(10013, "模型凭据无效，已降级为人工处理"),
    AI_BUDGET_EXHAUSTED(10014, "AI预算已用尽，已降级为规则建议"),

    /** 参数校验失败（@Valid 校验不通过） */
    PARAM_INVALID(40000, "参数校验失败"),

    /** 请求体格式错误，Jackson 无法解析 */
    REQUEST_BODY_UNREADABLE(40001, "请求体格式错误，无法解析"),

    /** 系统异常（对外固定文案，真实原因只写日志） */
    SYSTEM_ERROR(50000, "系统繁忙，请稍后重试");

    private final int code;

    private final String message;

    ErrorCode(int code, String message) {
        this.code = code;
        this.message = message;
    }

    public int getCode() {
        return code;
    }

    public String getMessage() {
        return message;
    }

}
