CREATE TABLE IF NOT EXISTS cache_invalidation (
 ticket_id BIGINT UNSIGNED NOT NULL PRIMARY KEY, generation BIGINT NOT NULL DEFAULT 0,
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS agent_action (
 action_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 actor_id BIGINT UNSIGNED NOT NULL, ticket_id BIGINT UNSIGNED NOT NULL,
 expected_version BIGINT NOT NULL, assignee_id BIGINT UNSIGNED NOT NULL,
 run_id CHAR(36) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 expires_at DATETIME(3) NOT NULL, result JSON NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 KEY idx_action_expiry(status,expires_at),
 CHECK(status IN ('PENDING','EXECUTED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS agent_run (
 run_id CHAR(36) NOT NULL PRIMARY KEY,actor_id BIGINT UNSIGNED NOT NULL,
 status VARCHAR(30) NOT NULL, model_calls INT NOT NULL DEFAULT 0,
 tool_calls INT NOT NULL DEFAULT 0, tokens_used INT NOT NULL DEFAULT 0,
 cost_ms BIGINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 KEY idx_run_actor(actor_id,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS agent_step (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 run_id CHAR(36) NOT NULL, tool_call_id VARCHAR(128) NOT NULL,
 tool_name VARCHAR(64) NOT NULL, outcome VARCHAR(30) NOT NULL,
 cost_ms BIGINT NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 KEY idx_step_run(run_id,id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS ai_usage_budget (
 actor_id BIGINT UNSIGNED NOT NULL,usage_date DATE NOT NULL,
 requests_used INT NOT NULL DEFAULT 0,tokens_used BIGINT NOT NULL DEFAULT 0,
 PRIMARY KEY(actor_id,usage_date)
) ENGINE=InnoDB;
